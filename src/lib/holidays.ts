export function holidayName(iso: string | null | undefined): string | null {
  if (!iso) return null;
  return HOLIDAYS[iso.slice(0, 10)] ?? null;
}

export function isRedDay(iso: string): boolean {
  const d = new Date(iso.slice(0, 4) + "-" + iso.slice(5, 7) + "-" + iso.slice(8, 10) + "T12:00:00");
  const day = d.getDay();
  return day === 0 || day === 6 || !!holidayName(iso);
}
